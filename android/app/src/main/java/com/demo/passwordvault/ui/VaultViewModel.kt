import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.Job
import kotlinx.coroutines.delay
import kotlinx.coroutines.isActive
import kotlinx.coroutines.launch
import kotlinx.coroutines.sync.Mutex
import kotlinx.coroutines.sync.withLock
import kotlinx.coroutines.withContext
import java.io.File

sealed interface Screen {
    data object Setup : Screen
    data object Locked : Screen
    data object Home : Screen
    data class Detail(val id: String) : Screen
    data class Edit(val id: String?) : Screen
    data object Generator : Screen
}

class VaultViewModel(app: Application) : AndroidViewModel(app) {
    private val store = VaultStore(File(app.filesDir, "vault.bin"))
    private val policy = AutoLockPolicy()
    private val throttle = UnlockThrottle()
    private val mutex = Mutex()
    private val generator = PasswordGenerator()
    private var session: VaultSession? = null
    private var clipboardJob: Job? = null

    var screen by mutableStateOf<Screen>(if (store.exists()) Screen.Locked else Screen.Setup)
        private set
    var entries by mutableStateOf<List<VaultEntry>>(emptyList())
        private set
    var query by mutableStateOf("")
    var busy by mutableStateOf(false)
        private set
    var error by mutableStateOf<String?>(null)
        private set
    /** הודעה קצרה (Snackbar). */
    var message by mutableStateOf<String?>(null)

    /** טיוטת עריכה – נשמרת ב-ViewModel (בזיכרון בלבד) כדי לשרוד סיבוב מסך. */
    var draft by mutableStateOf<VaultEntry?>(null)
    var generatorOptions by mutableStateOf(GeneratorOptions())
        private set
    var generated by mutableStateOf("")
        private set

    val visibleEntries: List<VaultEntry> get() = entries.search(query)

    init {
        regenerate()
        viewModelScope.launch {
            while (isActive) {
                delay(1_000)
                if (session != null && policy.shouldLock(now())) lock(auto = true)
            }
        }
    }

    private fun now() = SystemClock.elapsedRealtime()

    // ---------- מחזור חיים ----------
    fun onUserInteraction() = policy.onInteraction(now())
    fun onBackground() { if (session != null) policy.onBackground(now()) }
    fun onForeground() { if (session != null && policy.onForeground(now())) lock(auto = true) }

    // ---------- יצירה / פתיחה / נעילה ----------
    fun createVault(password: String, confirm: String) {
        if (busy) return
        error = when {
            password.length < 8 -> Txt.ERR_TOO_SHORT
            password != confirm -> Txt.ERR_MISMATCH
            else -> null
        }
        if (error != null) return
        val chars = password.toCharArray()
        busy = true
        viewModelScope.launch {
            try {
                val s = withContext(Dispatchers.Default) { store.create(chars, SampleData.entries(generator)) }
                opened(s)
            } catch (e: Exception) {
                error = Txt.ERR_GENERIC
            } finally {
                chars.fill('\u0000')
                busy = false
            }
        }
    }

    fun unlock(password: String) {
        if (busy) return
        val blocked = throttle.remainingBlockMillis(now())
        if (blocked > 0) {
            error = Txt.errBlocked((blocked + 999) / 1000)
            return
        }
        val chars = password.toCharArray()
        busy = true
        error = null
        viewModelScope.launch {
            try {
                val s = withContext(Dispatchers.Default) { store.unlock(chars) }
                throttle.onSuccess()
                opened(s)
            } catch (e: WrongPasswordException) {
                throttle.onFailure(now())
                val b = throttle.remainingBlockMillis(now())
                error = if (b > 0) Txt.errBlocked((b + 999) / 1000) else Txt.ERR_WRONG
            } catch (e: CorruptVaultException) {
                error = Txt.ERR_CORRUPT
            } catch (e: Exception) {
                error = Txt.ERR_GENERIC
            } finally {
                chars.fill('\u0000')
                busy = false
            }
        }
    }

    private fun opened(s: VaultSession) {
        session = s
        entries = s.entries
        query = ""
        error = null
        policy.onUnlocked(now())
        screen = Screen.Home
    }

    fun lock(auto: Boolean = false) {
        // קודם מסתירים הכול מהמסך, ואז מוחקים את המפתח (תחת מנעול, כדי לא להתנגש בשמירה).
        screen = Screen.Locked
        entries = emptyList()
        draft = null
        query = ""
        error = null
        message = if (auto) Txt.AUTO_LOCKED else null
        clearClipboardNow()
        viewModelScope.launch {
            mutex.withLock {
                session?.lock()
                session = null
            }
        }
    }

    // ---------- ניווט ----------
    fun openDetail(id: String) { screen = Screen.Detail(id) }

    fun openNew() {
        draft = VaultEntry(title = "")
        screen = Screen.Edit(null)
    }

    fun openEdit(id: String) {
        draft = entries.firstOrNull { it.id == id } ?: return
        screen = Screen.Edit(id)
    }

    fun openGenerator() { screen = Screen.Generator }

    fun back() {
        screen = when (val s = screen) {
            is Screen.Edit -> { draft = null; if (s.id != null) Screen.Detail(s.id) else Screen.Home }
            is Screen.Detail, Screen.Generator -> Screen.Home
            else -> s
        }
    }

    fun entry(id: String): VaultEntry? = entries.firstOrNull { it.id == id }

    // ---------- שינוי נתונים ----------
    fun saveDraft() {
        val d = draft ?: return
        val editingId = (screen as? Screen.Edit)?.id
        if (d.title.isBlank()) { error = Txt.ERR_TITLE_REQUIRED; return }
        error = null
        mutate(
            change = { list -> if (editingId == null) VaultOps.add(list, d) else VaultOps.update(list, d) },
            after = { draft = null; screen = Screen.Detail(d.id); message = Txt.SAVED },
        )
    }

    fun delete(id: String) {
        mutate(
            change = { list -> VaultOps.delete(list, id) },
            after = { screen = Screen.Home; message = Txt.DELETED },
        )
    }

    private fun mutate(change: (List<VaultEntry>) -> List<VaultEntry>, after: () -> Unit) {
        viewModelScope.launch {
            try {
                mutex.withLock {
                    val s = session ?: return@launch
                    val newList = change(s.entries)
                    withContext(Dispatchers.IO) { s.save(newList) }
                    entries = s.entries
                }
                after()
            } catch (e: Exception) {
                message = Txt.ERR_SAVE
            }
        }
    }

    // ---------- מחולל ----------
    fun updateGeneratorOptions(o: GeneratorOptions) {
        generatorOptions = o
        regenerate()
    }

    fun regenerate() {
        generated = if (PasswordGenerator.charSets(generatorOptions).isEmpty()) "" else generator.generate(generatorOptions)
    }

    // ---------- לוח העתקה ----------
    fun copyToClipboard(label: String, text: String) {
        val cm = getApplication<Application>().getSystemService(ClipboardManager::class.java) ?: return
        val clip = ClipData.newPlainText(label, text)
        // מסמן כתוכן רגיש: אנדרואיד 13+ לא יציג אותו בתצוגה המקדימה של הלוח
        clip.description.extras = PersistableBundle().apply {
            putBoolean("android.content.extra.IS_SENSITIVE", true)
        }
        cm.setPrimaryClip(clip)
        message = Txt.COPIED
        clipboardJob?.cancel()
        clipboardJob = viewModelScope.launch {
            delay(30_000)
            clearClipboardNow()
        }
    }

    private fun clearClipboardNow() {
        val job = clipboardJob ?: return
        clipboardJob = null
        job.cancel()
        val cm = getApplication<Application>().getSystemService(ClipboardManager::class.java) ?: return
        try {
            if (Build.VERSION.SDK_INT >= 28) cm.clearPrimaryClip()
            else cm.setPrimaryClip(ClipData.newPlainText("", ""))
        } catch (e: Exception) {
            // אין מה לעשות; לא כותבים ללוג.
        }
    }

    override fun onCleared() {
        session?.lock()
        session = null
        super.onCleared()
    }
}
