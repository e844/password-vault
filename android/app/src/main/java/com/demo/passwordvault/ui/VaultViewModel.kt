package com.demo.passwordvault.ui

import android.app.Application
import android.content.ClipData
import android.content.ClipboardManager
import android.os.Build
import android.os.PersistableBundle
import android.os.SystemClock
import androidx.compose.runtime.getValue
import androidx.compose.runtime.mutableStateOf
import androidx.compose.runtime.setValue
import androidx.lifecycle.AndroidViewModel
import androidx.lifecycle.viewModelScope
import com.demo.passwordvault.core.AutoLockPolicy
import com.demo.passwordvault.core.CorruptVaultException
import com.demo.passwordvault.core.GeneratorOptions
import com.demo.passwordvault.core.PasswordGenerator
import com.demo.passwordvault.core.SampleData
import com.demo.passwordvault.core.UnlockThrottle
import com.demo.passwordvault.core.VaultEntry
import com.demo.passwordvault.core.VaultOps
import com.demo.passwordvault.core.VaultSession
import com.demo.passwordvault.core.VaultStore
import com.demo.passwordvault.core.WrongPasswordException
