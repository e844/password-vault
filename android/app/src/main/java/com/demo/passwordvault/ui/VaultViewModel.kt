sealed interface Screen {
    data object Setup : Screen
    data object Locked : Screen
    data object Home : Screen
    data class Detail(val id: String) : Screen
    data class Edit(val id: String?) : Screen
    data object Generator : Screen
}

/** חלונות קופצים ברמת האפליקציה. */
sealed interface VaultDialog {
    data object ExportWarning : VaultDialog
    data object Restore : VaultDialog
    data object ChangeMaster : VaultDialog
    data object LockSettings : VaultDialog
    data object Update : VaultDialog
    data object Appearance : VaultDialog
}

class VaultViewModel(app: Application) : AndroidViewModel(app) {
    private val store = VaultStore(File(app.filesDir, "vault.bin"))
    private val prefs = app.getSharedPreferences("settings", Context.MODE_PRIVATE)
    private val policy = AutoLockPolicy()
    private val throttle = UnlockThrottle()
    private val mutex = Mutex()
    private val generator = PasswordGenerator()
    private var session: VaultSession? = null
    private var clipboardJob: Job? = null
    private var pendingRestore: Uri? = null

    var screen by mutableStateOf<Screen>(if (store.exists()) Screen.Locked else Screen.Setup)
        private set
    var entries by mutableStateOf<List<VaultEntry>>(emptyList())
        private set
    var query by mutableStateOf("")
    /** "all" או מפתח קטגוריה */
    var activeCategory by mutableStateOf("all")
    var busy by mutableStateOf(false)
        private set
    var error by mutableStateOf<String?>(null)
        private set
    var message by mutableStateOf<String?>(null)
    var dialog by mutableStateOf<VaultDialog?>(null)
    var dialogError by mutableStateOf<String?>(null)
    var autoLockMinutes by mutableStateOf(AutoLockPolicy.DEFAULT_MINUTES)
    var autofillOnLoad by mutableStateOf(false)
        private set

    /** טיוטת עריכה – בזיכרון בלבד, שורדת סיבוב מסך. */
    var draft by mutableStateOf<VaultEntry?>(null)
    var generatorOptions by mutableStateOf(GeneratorOptions())
        private set
    var generated by mutableStateOf("")
        private set

    /** תמונת רקע אישית – נשמרת רק בטלפון, בתיקייה הפרטית של האפליקציה. */
    var photo by mutableStateOf<ImageBitmap?>(null)
        private set
    private val photoFile = File(File(app.filesDir, "appearance"), "background.jpg")

    val visibleEntries: List<VaultEntry>
        get() = entries.filter { activeCategory == "all" || it.category == activeCategory }.search(query)

    init {
        autoLockMinutes = prefs.getInt("autoLockMinutes", AutoLockPolicy.DEFAULT_MINUTES)
            .takeIf { it in AutoLockPolicy.CHOICES_MINUTES } ?: AutoLockPolicy.DEFAULT_MINUTES
        policy.setMinutes(autoLockMinutes)
        autofillOnLoad = prefs.getBoolean(VaultHolder.PREF_AUTOFILL_ON_LOAD, false)
        regenerate()
        VaultHolder.current(app)?.let { opened(it) } // כבר פתוחה (מהמילוי האוטומטי או מפתיחה קודמת)
        viewModelScope.launch {
            photo = withContext(Dispatchers.IO) {
                try { BitmapFactory.decodeFile(photoFile.path)?.asImageBitmap() } catch (e: Exception) { null }
            }
        }
        viewModelScope.launch {
            while (isActive) {
                delay(1_000)
                // נועלים כשהזמן עבר (מהשימוש האחרון – באפליקציה או במילוי), או כשהכספת ננעלה מבחוץ
                val s = session
                if (s != null && VaultHolder.current(getApplication()) !== s) lock(auto = true)
            }
        }
    }

    private fun now() = SystemClock.elapsedRealtime()

    // ---------- מחזור חיים ----------
    fun onUserInteraction() {
        policy.onInteraction(now())
        if (session != null) VaultHolder.touch()
    }
    fun onBackground() { if (session != null) policy.onBackground(now()) }
    fun onForeground() {
        val s = session
        val shared = VaultHolder.current(getApplication())
        if (s != null && shared !== s) lock(auto = true)
        else if (s == null && shared != null && screen == Screen.Locked) opened(shared) // נפתחה מתוך המילוי האוטומטי
    }
    /** המסך כבה: במצב "רק בנעילת הטלפון" נועלים מיד; אחרת – לפי הזמן שנבחר. */
    fun onScreenOff() { if (session != null && autoLockMinutes == 0) lock(auto = true) }

    // ---------- יצירה / פתיחה / נעילה ----------
    fun createVault(password: String, confirm: String) {
        if (busy) return
        error = when {
            password.length < 8 -> Txt.ERR_TOO_SHORT
            password != confirm -> Txt.ERR_MISMATCH
            else -> null
        }
        if (error != null) return
        val chars = password.toCharArray()
        busy = true
        viewModelScope.launch {
            try {
                val s = withContext(Dispatchers.Default) { store.create(chars, SampleData.entries(generator)) }
                opened(s)
            } catch (e: Exception) {
                error = Txt.ERR_GENERIC
            } finally {
                chars.fill('\u0000')
                busy = false
            }
        }
    }

    fun unlock(password: String) {
        if (busy) return
        val blocked = throttle.remainingBlockMillis(now())
        if (blocked > 0) {
            error = Txt.errBlocked((blocked + 999) / 1000)
            return
        }
        val chars = password.toCharArray()
        busy = true
        error = null
        viewModelScope.launch {
            try {
                val s = withContext(Dispatchers.Default) { store.unlock(chars) }
                throttle.onSuccess()
                opened(s)
            } catch (e: WrongPasswordException) {
                throttle.onFailure(now())
                val b = throttle.remainingBlockMillis(now())
                error = if (b > 0) Txt.errBlocked((b + 999) / 1000) else Txt.ERR_WRONG
            } catch (e: CorruptVaultException) {
                error = Txt.ERR_CORRUPT
            } catch (e: Exception) {
                error = Txt.ERR_GENERIC
            } finally {
                chars.fill('\u0000')
                busy = false
            }
        }
    }

    private fun opened(s: VaultSession) {
        session = s
        VaultHolder.open(getApplication(), s)
        entries = s.entries
        query = ""
        activeCategory = "all"
        error = null
        policy.onUnlocked(now())
        screen = Screen.Home
    }

    fun lock(auto: Boolean = false) {
        screen = Screen.Locked
        entries = emptyList()
        draft = null
        query = ""
        activeCategory = "all"
        error = null
        dialog = null
        dialogError = null
        pendingRestore = null
        message = if (auto) Txt.AUTO_LOCKED else null
        VaultHolder.lock()
        clearClipboardNow()
        viewModelScope.launch {
            mutex.withLock {
                session?.lock()
                session = null
            }
        }
    }

    // ---------- ניווט ----------
    fun openDetail(id: String) { screen = Screen.Detail(id) }

    fun openNew() {
        draft = VaultEntry(title = "", category = if (activeCategory == "all") "general" else activeCategory)
        screen = Screen.Edit(null)
    }

    fun openEdit(id: String) {
        draft = entries.firstOrNull { it.id == id } ?: return
        screen = Screen.Edit(id)
    }

    fun openGenerator() { screen = Screen.Generator }

    fun back() {
        screen = when (val s = screen) {
            is Screen.Edit -> { draft = null; if (s.id != null) Screen.Detail(s.id) else Screen.Home }
            is Screen.Detail, Screen.Generator -> Screen.Home
            else -> s
        }
    }

    fun entry(id: String): VaultEntry? = entries.firstOrNull { it.id == id }

    fun categoryCount(key: String): Int = entries.count { it.category == key }

    // ---------- שינוי נתונים ----------
    fun saveDraft() {
        val d = draft ?: return
        val editingId = (screen as? Screen.Edit)?.id
        if (d.title.isBlank()) { error = Txt.ERR_TITLE_REQUIRED; return }
        error = null
        mutate(
            change = { list -> if (editingId == null) VaultOps.add(list, d) else VaultOps.update(list, d) },
            after = {
                draft = null
                if (activeCategory != "all" && activeCategory != d.category) activeCategory = "all"
                screen = Screen.Detail(d.id)
                message = Txt.SAVED
            },
        )
    }

    fun delete(id: String) {
        mutate(
            change = { list -> VaultOps.delete(list, id) },
            after = {
                if (activeCategory != "all" && entries.none { it.category == activeCategory }) activeCategory = "all"
                screen = Screen.Home
                message = Txt.DELETED
            },
        )
    }

    private fun mutate(change: (List<VaultEntry>) -> List<VaultEntry>, after: () -> Unit) {
        viewModelScope.launch {
            try {
                mutex.withLock {
                    val s = session ?: return@launch
                    val newList = change(s.entries)
                    withContext(Dispatchers.IO) { s.save(newList) }
                    entries = s.entries
                }
                after()
            } catch (e: Exception) {
                message = Txt.ERR_SAVE
            }
        }
    }

    // ---------- ייצוא / ייבוא / גיבוי ----------
    private fun stamp() = SimpleDateFormat("yyyy-MM-dd", Locale.ROOT).format(Date())
    fun csvFileName() = "PasswordVault-${stamp()}.csv"
    fun backupFileName() = "PasswordVault-backup-${stamp()}.pvault"

    private fun readUri(uri: Uri): ByteArray {
        val r = getApplication<Application>().contentResolver
        r.openInputStream(uri).use { input ->
            requireNotNull(input)
            val bytes = input.readBytes()
            if (bytes.size > 20 * 1024 * 1024) throw IllegalArgumentException("too big")
            return bytes
        }
    }

    private fun writeUri(uri: Uri, bytes: ByteArray) {
        val r = getApplication<Application>().contentResolver
        r.openOutputStream(uri, "wt").use { out -> requireNotNull(out).write(bytes) }
    }

    fun exportCsv(uri: Uri) {
        viewModelScope.launch {
            try {
                val count = mutex.withLock {
                    val s = session ?: return@launch
                    val text = Csv.export(s.entries)
                    withContext(Dispatchers.IO) { writeUri(uri, text.toByteArray(Charsets.UTF_8)) }
                    s.entries.size
                }
                message = Txt.exported(count)
            } catch (e: Exception) {
                message = Txt.ERR_FILE
            }
        }
    }

    fun importCsv(uri: Uri) {
        viewModelScope.launch {
            try {
                val parsed = withContext(Dispatchers.IO) { Csv.parseEntries(String(readUri(uri), Charsets.UTF_8)) }
                val r = mutex.withLock {
                    val s = session ?: return@launch
                    val r = VaultOps.import(s.entries, parsed.entries)
                    if (r.added > 0) withContext(Dispatchers.IO) { s.save(r.entries) }
                    entries = s.entries
                    r
                }
                message = Txt.imported(r.added, r.duplicates, parsed.skipped)
            } catch (e: Csv.UnrecognizedCsvException) {
                message = Txt.ERR_CSV
            } catch (e: Exception) {
                message = Txt.ERR_FILE
            }
        }
    }

    fun backup(uri: Uri) {
        viewModelScope.launch {
            try {
                mutex.withLock {
                    val s = session ?: return@launch
                    withContext(Dispatchers.IO) {
                        s.save(s.entries) // מוודא שהקובץ עדכני, ואז מעתיקים אותו – מוצפן כמו שהוא
                        writeUri(uri, store.encryptedBytes())
                    }
                }
                message = Txt.BACKED_UP
            } catch (e: Exception) {
                message = Txt.ERR_FILE
            }
        }
    }

    fun pickRestore(uri: Uri) {
        pendingRestore = uri
        dialogError = null
        dialog = VaultDialog.Restore
    }

    fun restore(password: String) {
        val uri = pendingRestore ?: return
        if (busy) return
        val chars = password.toCharArray()
        busy = true
        dialogError = null
        viewModelScope.launch {
            try {
                val incoming = withContext(Dispatchers.Default) { store.readBackup(withContext(Dispatchers.IO) { readUri(uri) }, chars) }
                val r = mutex.withLock {
                    val s = session ?: return@launch
                    val r = VaultOps.merge(s.entries, incoming)
                    withContext(Dispatchers.IO) { s.save(r.entries) }
                    entries = s.entries
                    r
                }
                pendingRestore = null
                dialog = null
                message = Txt.restored(r.added, r.updated)
            } catch (e: WrongPasswordException) {
                dialogError = Txt.ERR_WRONG
            } catch (e: CorruptVaultException) {
                dialogError = Txt.ERR_NOT_BACKUP
            } catch (e: Exception) {
                dialogError = Txt.ERR_FILE
            } finally {
                chars.fill('\u0000')
                busy = false
            }
        }
    }

    fun changeMaster(current: String, next: String, confirm: String) {
        if (busy) return
        dialogError = when {
            next.length < 8 -> Txt.ERR_TOO_SHORT
            next != confirm -> Txt.ERR_MISMATCH
            else -> null
        }
        if (dialogError != null) return
        val cur = current.toCharArray()
        val nxt = next.toCharArray()
        busy = true
        viewModelScope.launch {
            try {
                mutex.withLock {
                    val s = session ?: return@launch
                    withContext(Dispatchers.Default) {
                        store.unlock(cur).lock() // אימות הסיסמה הנוכחית
                        s.changePassword(nxt)
                    }
                }
                dialog = null
                message = Txt.MASTER_CHANGED
            } catch (e: WrongPasswordException) {
                dialogError = Txt.ERR_WRONG_CURRENT
            } catch (e: Exception) {
                dialogError = Txt.ERR_GENERIC
            } finally {
                cur.fill('\u0000')
                nxt.fill('\u0000')
                busy = false
            }
        }
    }

    fun toggleAutofillOnLoad() {
        autofillOnLoad = !autofillOnLoad
        prefs.edit().putBoolean(VaultHolder.PREF_AUTOFILL_ON_LOAD, autofillOnLoad).apply()
        message = if (autofillOnLoad) Txt.AUTOFILL_ON_LOAD_ON else Txt.AUTOFILL_ON_LOAD_OFF
    }

    fun setAutoLock(minutes: Int) {
        if (minutes !in AutoLockPolicy.CHOICES_MINUTES) return
        autoLockMinutes = minutes
        prefs.edit().putInt("autoLockMinutes", minutes).apply()
        policy.setMinutes(minutes)
        policy.onInteraction(now())
        dialog = null
        message = Txt.lockSaved(minutes)
    }

    // ---------- התאמה אישית ----------
    fun setPhoto(uri: Uri) {
        viewModelScope.launch {
            try {
                val bmp = withContext(Dispatchers.IO) {
                    val b = decodeScaled(uri, 1600)
                    photoFile.parentFile?.mkdirs()
                    photoFile.outputStream().use { b.compress(Bitmap.CompressFormat.JPEG, 86, it) }
                    b.asImageBitmap()
                }
                photo = bmp
                message = Txt.PHOTO_SAVED
            } catch (e: Exception) {
                message = Txt.PHOTO_ERROR
            }
        }
    }

    fun removePhoto() {
        photoFile.delete()
        photo = null
        message = Txt.PHOTO_REMOVED
    }

    /** מקטין את התמונה כך שהצלע הארוכה תהיה עד maxSide (וגם מסובב לפי EXIF באנדרואיד 9+). */
    private fun decodeScaled(uri: Uri, maxSide: Int): Bitmap {
        val resolver = getApplication<Application>().contentResolver
        if (Build.VERSION.SDK_INT >= 28) {
            val src = ImageDecoder.createSource(resolver, uri)
            return ImageDecoder.decodeBitmap(src) { decoder, info, _ ->
                val w = info.size.width
                val h = info.size.height
                val scale = maxSide.toFloat() / maxOf(w, h)
                if (scale < 1f) decoder.setTargetSize((w * scale).toInt().coerceAtLeast(1), (h * scale).toInt().coerceAtLeast(1))
                decoder.allocator = ImageDecoder.ALLOCATOR_SOFTWARE
            }
        }
        val bounds = BitmapFactory.Options().apply { inJustDecodeBounds = true }
        resolver.openInputStream(uri).use { BitmapFactory.decodeStream(it, null, bounds) }
        var sample = 1
        while (maxOf(bounds.outWidth, bounds.outHeight) / (sample * 2) >= maxSide) sample *= 2
        val opts = BitmapFactory.Options().apply { inSampleSize = sample }
        return resolver.openInputStream(uri).use { BitmapFactory.decodeStream(it, null, opts) } ?: throw IllegalArgumentException("not an image")
    }

    fun showDialog(d: VaultDialog) {
        dialogError = null
        dialog = d
    }

    fun dismissDialog() {
        dialog = null
        dialogError = null
        pendingRestore = null
    }

    // ---------- מחולל ----------
    fun updateGeneratorOptions(o: GeneratorOptions) {
        generatorOptions = o
        regenerate()
    }

    fun regenerate() {
        generated = if (PasswordGenerator.charSets(generatorOptions).isEmpty()) "" else generator.generate(generatorOptions)
    }

    // ---------- לוח העתקה ----------
    fun copyToClipboard(label: String, text: String) {
        val cm = getApplication<Application>().getSystemService(ClipboardManager::class.java) ?: return
        val clip = ClipData.newPlainText(label, text)
        // מסמן כתוכן רגיש: אנדרואיד 13+ לא יציג אותו בתצוגה המקדימה של הלוח
        clip.description.extras = PersistableBundle().apply {
            putBoolean("android.content.extra.IS_SENSITIVE", true)
        }
        cm.setPrimaryClip(clip)
        message = Txt.COPIED
        clipboardJob?.cancel()
        clipboardJob = viewModelScope.launch {
            delay(30_000)
            clearClipboardNow()
        }
    }

    private fun clearClipboardNow() {
        val job = clipboardJob ?: return
        clipboardJob = null
        job.cancel()
        val cm = getApplication<Application>().getSystemService(ClipboardManager::class.java) ?: return
        try {
            if (Build.VERSION.SDK_INT >= 28) cm.clearPrimaryClip()
            else cm.setPrimaryClip(ClipData.newPlainText("", ""))
        } catch (e: Exception) {
            // אין מה לעשות; לא כותבים ללוג.
        }
    }

    override fun onCleared() {
        // הכספת נשארת פתוחה (בזיכרון) למילוי האוטומטי עד שהזמן שנבחר עובר
        session = null
        super.onCleared()
    }
