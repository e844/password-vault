'use strict';
const { contextBridge, ipcRenderer } = require('electron');

// ממשק מצומצם בלבד לממשק המשתמש. אין גישה ל-Node או לקבצים.
contextBridge.exposeInMainWorld('vault', {
  state: () => ipcRenderer.invoke('state'),
  create: (password, confirm) => ipcRenderer.invoke('create', password, confirm),
  unlock: (password) => ipcRenderer.invoke('unlock', password),
  lock: () => ipcRenderer.invoke('lock'),
  list: () => ipcRenderer.invoke('list'),
  get: (id) => ipcRenderer.invoke('get', id),
  save: (entry) => ipcRenderer.invoke('save', entry),
  remove: (id) => ipcRenderer.invoke('delete', id),
  copyField: (id, field) => ipcRenderer.invoke('copyField', id, field),
  copyText: (text) => ipcRenderer.invoke('copyText', text),
  generate: (options) => ipcRenderer.invoke('generate', options),
  strength: (password) => ipcRenderer.invoke('strength', password),
  openUrl: (id) => ipcRenderer.invoke('openUrl', id),
  exportCsv: () => ipcRenderer.invoke('exportCsv'),
  importCsv: () => ipcRenderer.invoke('importCsv'),
  backup: () => ipcRenderer.invoke('backup'),
  restorePick: () => ipcRenderer.invoke('restorePick'),
  restoreApply: (password) => ipcRenderer.invoke('restoreApply', password),
  changeMaster: (current, next, confirm) => ipcRenderer.invoke('changeMaster', current, next, confirm),
  getSettings: () => ipcRenderer.invoke('getSettings'),
  setSettings: (s) => ipcRenderer.invoke('setSettings', s),
  browserInfo: () => ipcRenderer.invoke('browserInfo'),
  openExtensionFolder: () => ipcRenderer.invoke('openExtensionFolder'),
  copyExtensionsUrl: () => ipcRenderer.invoke('copyExtensionsUrl'),
  updateInfo: () => ipcRenderer.invoke('updateInfo'),
  checkUpdate: () => ipcRenderer.invoke('checkUpdate'),
  openUpdate: (kind) => ipcRenderer.invoke('openUpdate', kind),
  appearanceGet: () => ipcRenderer.invoke('appearanceGet'),
  appearancePick: () => ipcRenderer.invoke('appearancePick'),
  appearanceRemove: () => ipcRenderer.invoke('appearanceRemove'),
  appearanceColors: (on) => ipcRenderer.invoke('appearanceColors', on),
  activity: () => ipcRenderer.send('activity'),
  onLocked: (cb) => ipcRenderer.on('locked', (_e, info) => cb(info)),
});
